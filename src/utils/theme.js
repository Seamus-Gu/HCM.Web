function getBoxShadow(theme) {
  const color = boxShadow[theme]

  return `rgba(${color}, 0.4) 0 14px 26px -12px,rgba(${color}, 0.15) 0 4px 23px 0,rgba(${color}, 0.2) 0 8px 10px -5px`
}

export function getThemeColor(name) {
  return primary[name]
}

export function setLoginTheme(theme) {
  let root = document.querySelector(':root')
  let colors = []

  colors = colorList[theme]

  root.style.setProperty('--color-primary', primary[theme])
  root.style.setProperty('--color-primary-core', core[theme])
  root.style.setProperty('--color-primary-box-shadow', getBoxShadow(theme))

  colors.forEach((element, index) => {
    root.style.setProperty(`--color-primary-${index}`, element)
  })
}

export function setTheme(isDark, theme) {
  let root = document.querySelector(':root')
  let colors = []

  if (isDark) {
    document.querySelector('html').classList.add('dark')
    colors = darkList[theme]
  } else {
    document.querySelector('html').classList.remove('dark')
    colors = colorList[theme]
  }

  root.style.setProperty('--color-primary', primary[theme])
  root.style.setProperty('--color-primary-core', core[theme])
  root.style.setProperty('--color-primary-box-shadow', getBoxShadow(theme))

  colors.forEach((element, index) => {
    root.style.setProperty(`--color-primary-${index}`, element)
  })
}
